-- Run only in a throwaway PostgreSQL database with the migration installed.
-- auth.uid() should read request.jwt.claim.sub; auth.users must contain these IDs.
-- All changes roll back; no provider/network requests.
begin;
truncate public.ai_admissions, public.ai_interpretations;
update public.ai_provider_state set cooldown_until='-infinity';
update public.ai_runtime_config set user_per_minute=6,user_per_day=100,project_per_minute=12,project_per_day=450,user_concurrency=1,project_concurrency=2,lease_seconds=60,provider_cooldown_seconds=123,cache_ttl_seconds=300;
do $$
declare a jsonb; b jsonb; lease uuid; token uuid; replacement uuid; i integer; key text:=repeat('a',64);
begin
  assert not has_table_privilege('authenticated','public.ai_runtime_config','UPDATE');
  assert not has_table_privilege('authenticated','public.ai_interpretations','SELECT');
  assert not has_function_privilege('anon','public.ai_admit()','EXECUTE');
  assert not has_function_privilege('anon','public.ai_cache_claim(text)','EXECUTE');
  perform set_config('request.jwt.claim.sub','',true);
  begin perform public.ai_admit(); raise exception 'Anonymous admitted'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',true);
  a:=public.ai_admit(); assert (a->>'allowed')::boolean; lease:=(a->>'lease_id')::uuid;
  b:=public.ai_admit(); assert b->>'reason'='user_concurrency';
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',true);
  perform public.ai_release(lease);
  assert not (select released from public.ai_admissions where id=lease);
  update public.ai_runtime_config set project_concurrency=1;
  b:=public.ai_admit(); assert b->>'reason'='project_concurrency';
  update public.ai_admissions set expires_at=clock_timestamp()-interval '1 second' where id=lease;
  b:=public.ai_admit(); assert (b->>'allowed')::boolean;
  perform public.ai_release((b->>'lease_id')::uuid);
  truncate public.ai_admissions;
  update public.ai_runtime_config set project_concurrency=2;
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',true);
  for i in 1..6 loop a:=public.ai_admit(); assert (a->>'allowed')::boolean; perform public.ai_release((a->>'lease_id')::uuid); end loop;
  b:=public.ai_admit(); assert b->>'reason'='user_budget'; assert (b->>'retry_after_seconds')::int between 1 and 60;
  truncate public.ai_admissions;
  update public.ai_runtime_config set project_per_minute=1;
  a:=public.ai_admit(); perform public.ai_release((a->>'lease_id')::uuid);
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',true);
  b:=public.ai_admit(); assert b->>'reason'='project_budget';
  truncate public.ai_admissions;
  update public.ai_runtime_config set project_per_minute=12,user_per_day=1;
  a:=public.ai_admit(); perform public.ai_release((a->>'lease_id')::uuid);
  b:=public.ai_admit(); assert b->>'reason'='user_daily_budget';
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000001',true);
  update public.ai_runtime_config set project_per_day=1;
  b:=public.ai_admit(); assert b->>'reason'='daily_budget';
  truncate public.ai_admissions;
  update public.ai_runtime_config set project_per_day=450,user_per_day=100;
  a:=public.ai_admit(); lease:=(a->>'lease_id')::uuid;
  assert public.ai_provider_cooldown(lease)=123;
  perform public.ai_release(lease);
  b:=public.ai_admit(); assert b->>'reason'='provider_cooldown'; assert (b->>'retry_after_seconds')::int between 122 and 123;
  begin perform public.ai_provider_cooldown(lease); raise exception 'Released lease imposed cooldown'; exception when insufficient_privilege then null; end;
  a:=public.ai_cache_claim(key); assert a->>'status'='claimed'; token:=(a->>'claim_id')::uuid;
  b:=public.ai_cache_claim(key); assert b->>'status'='pending';
  update public.ai_interpretations set expires_at=clock_timestamp()-interval '1 second';
  b:=public.ai_cache_claim(key); assert b->>'status'='claimed'; replacement:=(b->>'claim_id')::uuid; assert replacement<>token;
  assert not public.ai_cache_complete(key,token,'{}');
  perform public.ai_cache_abandon(key,token);
  assert public.ai_cache_complete(key,replacement,'{"dietary_tag":"vegan"}');
  b:=public.ai_cache_claim(key); assert b->>'status'='hit'; assert b->'filters'='{"dietary_tag":"vegan"}'::jsonb;
  perform set_config('request.jwt.claim.sub','00000000-0000-4000-8000-000000000002',true);
  a:=public.ai_cache_claim(key); assert a->>'status'='claimed'; token:=(a->>'claim_id')::uuid;
  begin perform public.ai_cache_complete(key,token,'{"pickup_before":"2030-01-01T00:00:00Z"}'); raise exception 'Temporal filter cached'; exception when invalid_parameter_value then null; end;
  perform public.ai_cache_abandon(key,token);
  update public.ai_runtime_config set cache_max_entries=1;
  a:=public.ai_cache_claim(repeat('b',64)); assert a->>'status'='claimed';
  b:=public.ai_cache_claim(repeat('c',64)); assert b->>'status'='pending';
  assert (select count(*) from public.ai_interpretations)=1;
  raise notice 'PASS: identity, grants, user/project concurrency, expiry, minute/day budgets, configured cooldown, cache isolation/dedup/stale tokens/TTL/cap';
end $$;
rollback;
